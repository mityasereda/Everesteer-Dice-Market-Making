"""Write adaptive-reader opponents: my own learning estimator with a real agent's quoting habits.

    python3 analysis/make_adaptive.py opponents/fits.json agent.py opponents

For each fitted real agent this copies agent.py and replaces its PARAMS: half widths from the agent's mean width at
each step (rounded to 0.5), hide0 from its step-0 default share, and skew from its fitted position coefficient.
Unlike the static imitations (imit_*.py) these learn during the match and reach about the real agents' accuracy
(mid RMSE about 3.0 at step 3). They share my estimator, so they are good at reading but copy only the quoting habits.
"""
import json
import re
import sys
from pathlib import Path

NAMES = {"Docsdadi": "docsdadi", "zudvarnoki": "zudvarnoki", "MPP": "mpp", "billhwang": "billhwang",
         "momarci13": "momarci13", "yurko_mud": "yurko", "Joshua_Karat": "joshua", "leobgg": "leobgg",
         "house pro": "housepro"}
fits = json.load(open(sys.argv[1]))
src = Path(sys.argv[2]).read_text()
out = Path(sys.argv[3])
LAM = float(sys.argv[4]) if len(sys.argv) > 4 else 100.0      # learning strength of the copies
PREFIX = sys.argv[5] if len(sys.argv) > 5 else "adapt"


def mean_width(step):
    return sum(float(k) * v for k, v in step["widths"].items())


for label, short in NAMES.items():
    f = fits[label]
    half = [max(0.5, round(mean_width(s) * 2.0) / 4.0) for s in f["steps"]]   # half width on the 0.25 grid, at least 0.5
    skew = [-s["w"][-1] for s in f["steps"][1:] if s["n"]]
    skew = min(1.0, max(0.0, sum(skew) / len(skew))) if skew else 0.4
    params = (f"PARAMS = dict(\n    half=({', '.join(f'{h:.2f}' for h in half)}),\n    skew={skew:.2f},\n"
              f"    lam={LAM:.1f},\n    hide0={f['p0'] > 0.5},\n)")
    new, k = re.subn(r"PARAMS = dict\(.*?\n\)", params, src, count=1, flags=re.S)
    assert k == 1
    header = f"# Adaptive-reader opponent with the quoting habits of {label}. Generated by analysis/make_adaptive.py.\n"
    (out / f"{PREFIX}_{short}.py").write_text(header + new)
    print(f"{PREFIX}_{short}.py  half={half} skew={skew:.2f} hide0={f['p0'] > 0.5}")
